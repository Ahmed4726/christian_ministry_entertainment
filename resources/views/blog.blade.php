                        <p class="blog-text">Network marketing and outreach ministries have a common thread of reaching as many people as possible to spread their word. Those who swear for and/or against network marketing cite the 96% high failure/dropout rate while others talk about their 6 figure income. Network marketing companies bottom line is profits at the expense of its distributors who must buy their products to sell to end users who many just happen to be their family and friends. This easy way to start a business requires start-up costs of $100.00+ and little to no experience in direct sales. Ambitious entrepreneurs are lured into this net with potential rewards of unlimited income but when the dream goes bust friends turn into enemies and families are left holding the bag of unfulfilled dream dust.</p>

<p class="blog-text">Separately, networking and marketing are both good and positive features but together they can become a toxic mixture of greed and gain. Unscrupulous business practices take sound business principles leading to get rich quick pyramid schemes and eventually a scam labeling alert. Once embraced as a darling of entrepreneurship, network marketing is shunned by many as a disgraced misguided mistress of business illegitimate mismanagement practices.</p>

<p class="blog-text">Like many who are skeptical about using a network marketing model in business, I was not a fan to say the least and to be honest, many despised even loathed the model in general but I felt the Lord leading me to this model for ministry purposes. I had doubts about modeling my ministry using network marketing but I believe and know the Lord is saying it’s not of the devil or evil or a scam but networking marketing can become those things in the wrong hands of those who love money and labor to be rich.</p>

<p class="blog-text">Network marketing is a model that can be used or misused depending on who’s using it for what purposes. How does network marketing benefits Rejoice Christian Ministry? As a marketplace ministry, networking and marketing is essential to our success. Networking builds relationships for both ministry and business while marketing supports our business and professional financial base. Our ministry uses a 7 X 5 networking matrix that has a 40% payout rate at $50.00 per month + a 50% monthly fundraiser + an additional daily mini-matrix of 3-7% for our purchase rebate plan. With up to a 97% payout success not failure rate to our partners, our ministry outperforms any competition while dispelling all scams and schemes that misuses funds for financial gain.</p>

<p class="blog-text">Rejoice Christian Ministry does not have distributors or products but instead we network, advertise, market and promote our business and professional partners’ products and services at a cost of only $50.00 per month through our community events, programs and services. We also pay our businesses and professionals to serve as our paid life skills business mentors and apprentices as well as provide free and discounted services to our members and partners. Serving communities through the services, programs and events we provide establishes a local and global leadership role in all communities now and in the future.</p>
